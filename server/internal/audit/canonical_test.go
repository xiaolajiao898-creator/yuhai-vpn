func TestJCSStringSubsetUTF16AndEscapes(t *testing.T) {
	// U+1F600 starts with UTF-16 D83D, so it sorts before U+E000 even though
	// UTF-8/code-point sorting gives the opposite order (RFC 8785 3.2.3).
	got, err := jcs(map[string]any{"\ue000": "last", "😀": "second", "a": map[string]any{"z": nil, "a": "<>&/\u2028\u2029\b\t\n\f\r\x0f\"\\"}})
	want := "{\"a\":{\"a\":\"<>&/\u2028\u2029\\b\\t\\n\\f\\r\\u000f\\\"\\\\\",\"z\":null},\"😀\":\"second\",\"\ue000\":\"last\"}"
	if err != nil || string(got) != want {
		t.Fatalf("canonical bytes\ngot %q\nwant %q\nerr %v", got, want, err)
	}
	for _, v := range []any{float64(1), json.Number("1"), int64(9007199254740993), []any{"array"}, "\xff"} {
		if _, err := jcs(v); err == nil {
			t.Fatalf("accepted unsupported JCS input %T", v)
		}
	}
}

func TestAuditHashIndependentFixedVector(t *testing.T) {
	admin, target, approval := int64(7), int64(9), int64(12)
	r := record{ID: 9007199254740993, PrevHash: zeroHash(), CreatedAt: time.Date(2035, 1, 2, 3, 4, 5, 123456000, time.UTC), Event: Event{AdminUserID: &admin, ActionCode: "app.version.publish", TargetType: "app_version", TargetID: &target, RequestID: "req-1", IP: "2001:db8::1", UserAgent: "test/1", Result: "SUCCESS", StepUpVerified: true, ApprovalID: &approval}}
	before := map[string]any{"status": "DRAFT"}
	after := map[string]any{"status": "PUBLISHED", "version_code": "9007199254740993"}
	got, err := hashRecord(r, before, after)
	// Independently computed from literal sorted UTF-8 JSON + 64 ASCII zeros
	// using Python hashlib, not an expected value generated by this encoder.
	const want = "1aae719f789722937d25c161093f8323b2d4564f64af9c222418a4b68397e595"
	if err != nil || got != want {
		t.Fatal(got, err)
	}
	r.ID++
	changed, _ := hashRecord(r, before, after)
	if changed == want {
		t.Fatal("BIGINT identity omitted or rounded")
	}
}

func TestSnapshotRejectsSensitiveAmbiguousAndUnboundedInput(t *testing.T) {
	bad := []string{
		`{"password":"x"}`, `{"totp_secret":"x"}`, `{"access_token":"x"}`, `{"private_key":"x"}`, `{"Token":"x"}`,
		`{"status":"DRAFT","status":"PUBLISHED"}`, `{"st\u0061tus":"DRAFT","status":"PUBLISHED"}`,
		`{"version_code":1}`, `{"version_code":9007199254740993}`, `{"version_code":1e100}`, `{"version_code":"9223372036854775808"}`,
		`{"status":{"name":"hidden"}}`, `{"status":["x"]}`, `[]`, `{"status":true}`, `{"enabled":"true"}`,
		`{"name":"\ud800"}`, `{"name":"\udc00"}`, `{"name":"\ud800\ud800"}`, `{"name":"\u0000"}`,
		`{"name":"Bearer secret-value"}`, `{"decision_note":"private_key=secret-value"}`, `{"payload":"raw request"}`,
		`{"address":"TR7NHqjeKQxGTCi8q8ZY4pL8otSzgjLj6t"}`, `{"network":"TRON"}`,
		`{"status":"DRAFT"} {}`, `{"status":"DRAFT",}`, "{\"name\":\"\xff\"}",
		`{"decision_note":"` + strings.Repeat("字", 501) + `"}`, strings.Repeat(" ", maxSnapshotBytes) + "null",
	}
	for _, raw := range bad {
		t.Run(raw[:min(len(raw), 45)], func(t *testing.T) {
			if _, _, err := snapshot([]byte(raw)); err == nil {
				t.Fatalf("unsafe snapshot accepted: %.100s", raw)
			}
		})
	}
	for _, raw := range []string{`null`, `{}`, `{"enabled":true,"status":null}`, `{"version_code":"9007199254740993"}`, `{"name":"\ud83d\ude00"}`, `{"decision_note":"已核对版本文件，允许发布"}`} {
		if _, _, err := snapshot([]byte(raw)); err != nil {
			t.Fatalf("safe snapshot rejected: %s: %v", raw, err)
		}
	}
}

func TestAuditRejectsBadParametersWithoutDatabase(t *testing.T) {
	s := &Service{}
	if err := s.Append(context.Background(), nil, Event{}); err == nil {
		t.Fatal("nil transaction accepted")
	}
	for _, in := range []struct {
		page, size     int
		action, result string
	}{{-1, 20, "", ""}, {1, 51, "", ""}, {1, -1, "", ""}, {1000001, 20, "", ""}, {1, 20, "x' OR true", ""}, {1, 20, "", "ANY"}} {
		if _, err := s.List(context.Background(), in.page, in.size, in.action, in.result); err == nil {
			t.Fatal("bad list params accepted", in)
		}
	}
	for _, ids := range [][2]int64{{0, 1}, {-1, 5}, {3, 2}} {
		if _, err := s.Verify(context.Background(), ids[0], ids[1]); err == nil {
			t.Fatal("bad range accepted", ids)
		}
	}
	for _, e := range []Event{{ActionCode: "valid", RequestID: "req", Result: "ANY"}, {ActionCode: "invalid action", RequestID: "req", Result: "SUCCESS"}, {ActionCode: "valid", RequestID: strings.Repeat("r", 33), Result: "SUCCESS"}, {ActionCode: "valid", RequestID: "req", IP: "10.0.0.1/24", Result: "SUCCESS"}, {ActionCode: "valid", RequestID: "req", UserAgent: "header\nX-Token: token", Result: "SUCCESS"}} {
		if normalizeEvent(&e) == nil {
			t.Fatal("bad event accepted")
		}
	}
}
